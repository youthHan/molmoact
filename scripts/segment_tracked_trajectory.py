"""Segment tracked gripper trajectories by detecting reset points.

This utility ingests the JSON trajectory generated by
``track_gripper_trajectory.py`` and identifies indices where the gripper
returns to a starting pose at the beginning of a new video/demo.

Usage example::

    python3 MolmoAct/scripts/segment_tracked_trajectory.py \
        --trajectory run_01_traj.json \
        --shift-threshold 60 --steady-window 6 \
        --steady-threshold 4 --anchor-threshold 6 \
        --steady-outliers 1 --history-window 6 \
        --history-threshold 6 --history-outliers 0 \
        --min-segment-length 20 \
        --min-gap 40 --output run_01_segments.json

Detection heuristic:
1. Compute per-frame displacements using ``smoothed_x/smoothed_y`` if
   available, otherwise raw ``x/y``.
2. Mark a frame as a candidate boundary when the displacement from the
   previous frame exceeds ``--shift-threshold``.
3. Confirm a boundary only if the next ``--steady-window`` frames remain mostly
   stable (per-frame displacement <= ``--steady-threshold``) *and* stay close to
   the candidate frame (distance <= ``--anchor-threshold``). A small number of
   spikes can be tolerated via ``--steady-outliers``.
4. Reject a boundary if the candidate frame is still close to the preceding
   ``--history-window`` frames (distance <= ``--history-threshold``). This
   prevents short bursts of outliers from cutting a long segment.
5. Task instruction changes (decoded from parquet) always form hard boundaries.
   Motion-based boundaries honor ``--min-segment-length`` and ``--max-frames-per-segment``.

Confirmed boundaries split the trajectory into contiguous segments. Each
segment can optionally be written to JSON or summarized on stdout.
"""
from __future__ import annotations

import argparse
import json
import math
import glob
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

try:  # optional dependency for task extraction from parquet
    import pyarrow.parquet as pq
except Exception:  # pragma: no cover
    pq = None


@dataclass
class TrajectoryPoint:
    frame_idx: int  # local row index within a parquet shard
    total_frame_idx: int  # global row index across concatenated shards
    patch_idx: int
    x: float
    y: float
    score: float
    smoothed_x: float
    smoothed_y: float
    parquet_idx: Optional[int]
    task: Optional[str] = None

    @classmethod
    def from_raw(cls, data: dict) -> "TrajectoryPoint":
        sx = data.get("smoothed_x")
        sy = data.get("smoothed_y")
        frame_idx = int(data.get("frame_idx", 0))
        total_idx = int(data.get("total_frame_idx", frame_idx))
        parquet_idx = data.get("parquet_idx")
        parquet_idx = int(parquet_idx) if parquet_idx is not None else None
        task = data.get("task")
        return cls(
            frame_idx=frame_idx,
            total_frame_idx=total_idx,
            patch_idx=int(data["patch_idx"]),
            x=float(data["x"]),
            y=float(data["y"]),
            score=float(data.get("score", 0.0)),
            smoothed_x=float(sx if sx is not None else data["x"]),
            smoothed_y=float(sy if sy is not None else data["y"]),
            parquet_idx=parquet_idx,
            task=task,
        )

    def position(self) -> tuple[float, float]:
        return (self.smoothed_x, self.smoothed_y)


@dataclass
class Segment:
    start_index: int  # index within trajectory list
    end_index: int
    length: int
    start_total_frame: int
    end_total_frame: int
    start_local_frame: int
    end_local_frame: int
    parquet_idx: Optional[int]
    task: Optional[str]

    def to_dict(self) -> dict:
        return {
            "start_index": self.start_index,
            "end_index": self.end_index,
            "length": self.length,
            "start_total_frame": self.start_total_frame,
            "end_total_frame": self.end_total_frame,
            "start_frame": self.start_local_frame,
            "end_frame": self.end_local_frame,
            "parquet_idx": self.parquet_idx,
            "task": self.task,
        }


def load_trajectory(path: Path) -> List[TrajectoryPoint]:
    data = json.loads(path.read_text())
    if not isinstance(data, Sequence):
        raise ValueError("Trajectory JSON must be a list of objects")
    return [TrajectoryPoint.from_raw(item) for item in data]


def displacement(a: TrajectoryPoint, b: TrajectoryPoint) -> float:
    ax, ay = a.position()
    bx, by = b.position()
    return math.hypot(bx - ax, by - ay)


def expand_parquet_tokens(tokens: Sequence[str]) -> List[Path]:
    paths: List[Path] = []
    for token in tokens:
        expanded = os.path.expanduser(token)
        candidate = Path(expanded)
        if candidate.is_dir():
            paths.extend(sorted(candidate.glob("*.parquet")))
            continue
        if candidate.is_file() and candidate.suffix == ".parquet":
            paths.append(candidate)
            continue
        for match in glob.glob(expanded, recursive=True):
            match_path = Path(match)
            if match_path.is_file() and match_path.suffix == ".parquet":
                paths.append(match_path)
    unique: List[Path] = []
    seen = set()
    for path in sorted(paths):
        resolved = path.resolve()
        if resolved not in seen:
            seen.add(resolved)
            unique.append(resolved)
    return unique


def attach_tasks(
    traj: Sequence[TrajectoryPoint],
    parquet_tokens: Sequence[str],
    task_column: str,
) -> None:
    if pq is None:
        raise RuntimeError("pyarrow is required for --parquet task extraction")
    files = expand_parquet_tokens(parquet_tokens)
    if not files:
        raise FileNotFoundError("No parquet files located for task extraction")

    by_shard: Dict[int, Dict[int, TrajectoryPoint]] = {}
    for pt in traj:
        if pt.task is not None:
            continue
        if pt.parquet_idx is None:
            continue
        shard = by_shard.setdefault(pt.parquet_idx, {})
        shard[pt.frame_idx] = pt

    for shard_idx, index_map in by_shard.items():
        if shard_idx < 0 or shard_idx >= len(files):
            continue
        path = files[shard_idx]
        pf = pq.ParquetFile(path)
        metadata = pf.metadata
        num_groups = metadata.num_row_groups if metadata is not None else 1
        offset = 0
        for rg_idx in range(num_groups):
            table = pf.read_row_group(rg_idx, columns=[task_column])
            rows = table.to_pylist()
            for local_offset, row in enumerate(rows):
                frame_idx = offset + local_offset
                target = index_map.get(frame_idx)
                if target is None:
                    continue
                value = row.get(task_column) if isinstance(row, dict) else row
                target.task = parse_task(value)
            offset += len(rows)


def parse_task(conversations: Optional[str]) -> Optional[str]:
    if conversations in (None, ""):
        return None
    try:
        if isinstance(conversations, str):
            data = json.loads(conversations)
        else:
            data = conversations
    except Exception:
        return None
    if isinstance(data, dict):
        values = data.get("value")
    elif isinstance(data, list):
        values = data
    else:
        return None
    if not values:
        return None
    first = values[0]
    if isinstance(first, dict):
        text = first.get("value") or first.get("text")
    else:
        text = first
    if not text:
        return None
    if not isinstance(text, str):
        return None
    sentence = re.split(r"[.!?]", text.strip(), maxsplit=1)[0]
    return sentence.strip()


def detect_boundaries(
    traj: Sequence[TrajectoryPoint],
    shift_threshold: float,
    steady_window: int,
    steady_threshold: float,
    steady_outliers: int,
    anchor_threshold: float,
    history_window: int,
    history_threshold: float,
    history_outliers: int,
    min_gap: int,
    min_segment_length: int,
) -> List[int]:
    if len(traj) < 2:
        return [0]

    boundary_flags: Dict[int, bool] = {0: True}
    last_task = traj[0].task
    for idx in range(1, len(traj)):
        task = traj[idx].task
        if task is not None and last_task is not None and task != last_task:
            boundary_flags[idx] = True
        if task is not None:
            last_task = task

    mandatory_bounds = sorted(idx for idx, mandatory in boundary_flags.items() if mandatory)
    mandatory_bounds.append(len(traj))

    for b_idx in range(len(mandatory_bounds) - 1):
        start = mandatory_bounds[b_idx]
        end = mandatory_bounds[b_idx + 1]
        last_boundary = start
        i = start + 1
        while i < end:
            step = displacement(traj[i - 1], traj[i])
            if step >= shift_threshold:
                history_ok = True
                similar = 0
                for j in range(1, history_window + 1):
                    prev_idx = i - j
                    if prev_idx < start:
                        break
                    if displacement(traj[prev_idx], traj[i]) <= history_threshold:
                        similar += 1
                        if similar > history_outliers:
                            history_ok = False
                            break
                if not history_ok:
                    i += 1
                    continue

                window_ok = True
                outliers = 0
                for j in range(1, steady_window + 1):
                    idx = i + j
                    if idx >= end:
                        window_ok = False
                        break
                    step_delta = displacement(traj[idx - 1], traj[idx])
                    anchor_delta = displacement(traj[i], traj[idx])
                    if step_delta > steady_threshold or anchor_delta > anchor_threshold:
                        outliers += 1
                        if outliers > steady_outliers:
                            window_ok = False
                            break
                if window_ok and i - last_boundary >= min_gap:
                    boundary_flags.setdefault(i, False)
                    last_boundary = i
                    i += steady_window
                    continue
            i += 1

    sorted_bounds = sorted(boundary_flags.items())
    final_bounds: List[int] = []
    if not sorted_bounds:
        return [0]

    final_bounds.append(sorted_bounds[0][0])
    last_kept_idx = sorted_bounds[0][0]

    for idx, mandatory in sorted_bounds[1:]:
        segment_len = idx - last_kept_idx
        if mandatory:
            # ensure preceding optional boundaries are removed if they cause short segments
            while segment_len < min_segment_length and len(final_bounds) > 0:
                prev_idx = final_bounds[-1]
                if boundary_flags.get(prev_idx, True):
                    break
                final_bounds.pop()
                if final_bounds:
                    last_kept_idx = final_bounds[-1]
                else:
                    last_kept_idx = sorted_bounds[0][0]
                segment_len = idx - last_kept_idx
                if not final_bounds:
                    break
            final_bounds.append(idx)
            last_kept_idx = idx
        else:
            if segment_len >= min_segment_length:
                final_bounds.append(idx)
                last_kept_idx = idx

    # tail check: ensure final segment length meets minimum when boundary optional
    total_len = len(traj)
    if final_bounds:
        last_idx = final_bounds[-1]
        if total_len - last_idx < min_segment_length and not boundary_flags.get(last_idx, True):
            final_bounds.pop()

    return final_bounds or [0]


def build_segments(boundaries: Sequence[int], traj: Sequence[TrajectoryPoint], max_frames: Optional[int]) -> List[Segment]:
    segments: List[Segment] = []
    total_len = len(traj)
    sorted_bounds = sorted(set(boundaries))
    for idx, start in enumerate(sorted_bounds):
        end = total_len - 1 if idx == len(sorted_bounds) - 1 else sorted_bounds[idx + 1] - 1
        while max_frames and (end - start + 1) > max_frames:
            split_end = start + max_frames - 1
            segments.append(_segment_from_range(traj, start, split_end))
            start = split_end + 1
        segments.append(_segment_from_range(traj, start, end))
    return segments


def _segment_from_range(traj: Sequence[TrajectoryPoint], start: int, end: int) -> Segment:
    start_pt = traj[start]
    end_pt = traj[end]
    parquet_idx = start_pt.parquet_idx
    task_label = start_pt.task
    homogeneous = True
    for pos in range(start + 1, end + 1):
        pt = traj[pos]
        if pt.parquet_idx != parquet_idx:
            parquet_idx = None
        if task_label is not None and pt.task != task_label:
            homogeneous = False
    if not homogeneous:
        task_label = None
    return Segment(
        start_index=start,
        end_index=end,
        length=end - start + 1,
        start_total_frame=start_pt.total_frame_idx,
        end_total_frame=end_pt.total_frame_idx,
        start_local_frame=start_pt.frame_idx,
        end_local_frame=end_pt.frame_idx,
        parquet_idx=parquet_idx,
        task=task_label,
    )


def dump_segments(segments: Sequence[Segment]) -> None:
    print("Detected segments:")
    for seg in segments:
        print(
            f"- span idx[{seg.start_index}->{seg.end_index}] total[{seg.start_total_frame}->{seg.end_total_frame}]"
            f" len={seg.length} parquet={seg.parquet_idx} task={seg.task}"
        )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Segment tracked trajectories by detecting restarts")
    parser.add_argument("--trajectory", required=True, help="Path to trajectory JSON from track_gripper_trajectory.py")
    parser.add_argument("--shift-threshold", type=float, default=40.0, help="Min displacement (pixels) to consider a restart")
    parser.add_argument("--steady-window", type=int, default=5, help="Frames to verify steady motion after the shift")
    parser.add_argument(
        "--steady-threshold",
        type=float,
        default=5.0,
        help="Max per-frame displacement within steady window",
    )
    parser.add_argument(
        "--steady-outliers",
        type=int,
        default=0,
        help="Number of allowable spikes above the steady threshold inside the window",
    )
    parser.add_argument(
        "--anchor-threshold",
        type=float,
        default=5.0,
        help="Max distance from the candidate frame within the steady window",
    )
    parser.add_argument(
        "--history-window",
        type=int,
        default=5,
        help="Frames before the candidate that must differ from the candidate",
    )
    parser.add_argument(
        "--history-threshold",
        type=float,
        default=6.0,
        help="Maximum distance considered 'similar' to preceding history",
    )
    parser.add_argument(
        "--history-outliers",
        type=int,
        default=0,
        help="Allowed number of history frames still close to the candidate",
    )
    parser.add_argument(
        "--min-segment-length",
        type=int,
        default=5,
        help="Minimum allowable length (frames) for a segment boundary",
    )
    parser.add_argument(
        "--max-frames-per-segment",
        type=int,
        default=None,
        help="Maximum allowed frames per segment (segments are split if longer)",
    )
    parser.add_argument(
        "--parquet",
        action="append",
        default=[],
        help="Parquet file(s)/directories/globs to extract task descriptions",
    )
    parser.add_argument(
        "--task-column",
        default="conversations",
        help="Column containing task descriptions (JSON string)",
    )
    parser.add_argument("--min-gap", type=int, default=30, help="Minimum frames between restart boundaries")
    parser.add_argument("--output", help="Optional path to write segments JSON")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    traj_path = Path(args.trajectory)
    traj = load_trajectory(traj_path)
    if not traj:
        print("[WARN] Empty trajectory; nothing to segment")
        return

    if args.parquet:
        attach_tasks(traj, args.parquet, args.task_column)

    boundaries = detect_boundaries(
        traj,
        shift_threshold=args.shift_threshold,
        steady_window=args.steady_window,
        steady_threshold=args.steady_threshold,
        steady_outliers=args.steady_outliers,
        anchor_threshold=args.anchor_threshold,
        history_window=args.history_window,
        history_threshold=args.history_threshold,
        history_outliers=args.history_outliers,
        min_gap=args.min_gap,
        min_segment_length=args.min_segment_length,
    )
    segments = build_segments(boundaries, traj, args.max_frames_per_segment)
    dump_segments(segments)

    if args.output:
        payload = {
            "trajectory": str(traj_path),
            "shift_threshold": args.shift_threshold,
            "steady_window": args.steady_window,
            "steady_threshold": args.steady_threshold,
            "steady_outliers": args.steady_outliers,
            "anchor_threshold": args.anchor_threshold,
            "history_window": args.history_window,
            "history_threshold": args.history_threshold,
            "history_outliers": args.history_outliers,
            "max_frames_per_segment": args.max_frames_per_segment,
            "task_column": args.task_column if args.parquet else None,
            "min_segment_length": args.min_segment_length,
            "min_gap": args.min_gap,
            "segments": [seg.to_dict() for seg in segments],
        }
        Path(args.output).write_text(json.dumps(payload, indent=2))
        print(f"[INFO] Wrote segments to {args.output}")


if __name__ == "__main__":
    main()
